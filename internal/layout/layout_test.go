package layout

import (
	"math"
	"testing"

	"github.com/lukehoban/gobrowser2/internal/css"
	"github.com/lukehoban/gobrowser2/internal/dom"
	"github.com/lukehoban/gobrowser2/internal/html"
	"github.com/lukehoban/gobrowser2/internal/style"
)

type page struct {
	doc    *dom.Node
	root   *Box
	height float64
}

func layoutHTML(t *testing.T, src, sheet string, width float64) *page {
	t.Helper()
	doc := html.Parse(src)
	var sheets []*css.Stylesheet
	if sheet != "" {
		sheets = append(sheets, css.Parse(sheet))
	}
	root := Build(doc, style.Compute(doc, sheets, width), nil)
	if root == nil {
		t.Fatal("Build returned nil")
	}
	return &page{doc: doc, root: root, height: Layout(root, width)}
}

// box returns the box generated by the element with the given id.
func (p *page) box(t *testing.T, id string) *Box {
	t.Helper()
	var node *dom.Node
	p.doc.Walk(func(n *dom.Node) bool {
		if v, ok := n.Attr("id"); ok && v == id && node == nil {
			node = n
		}
		return node == nil
	})
	if node == nil {
		t.Fatalf("no element with id %q", id)
	}
	var found *Box
	var walk func(b *Box)
	walk = func(b *Box) {
		if found != nil {
			return
		}
		if b.Node == node {
			found = b
			return
		}
		for _, c := range b.Children {
			walk(c)
		}
		for _, it := range b.Inline {
			if it.Box != nil {
				walk(it.Box)
			}
		}
	}
	walk(p.root)
	if found == nil {
		t.Fatalf("no box for #%s", id)
	}
	return found
}

func approx(a, b float64) bool { return math.Abs(a-b) < 0.5 }

func checkRect(t *testing.T, name string, b *Box, x, y, w, h float64) {
	t.Helper()
	bx, by, bw, bh := b.BorderBox()
	if !approx(bx, x) || !approx(by, y) || !approx(bw, w) || !approx(bh, h) {
		t.Errorf("%s border box = (%v,%v %vx%v), want (%v,%v %vx%v)", name, bx, by, bw, bh, x, y, w, h)
	}
}

func TestBlockLayout(t *testing.T) {
	p := layoutHTML(t, `<!DOCTYPE html><body>
<div id="a" style="height: 50px; margin-bottom: 20px"></div>
<div id="b" style="height: 30px; margin-top: 10px; padding: 5px; border: 2px solid black"></div>
<div id="c" style="width: 200px; height: 10px; margin: 0 auto"></div>
<div id="d" style="width: 50%; height: 10px; margin-left: 10px"></div>
</body>`, "", 800)
	// body has an 8px margin; a and b's margins collapse to 20px.
	checkRect(t, "a", p.box(t, "a"), 8, 8, 784, 50)
	checkRect(t, "b", p.box(t, "b"), 8, 78, 784, 44)
	checkRect(t, "c", p.box(t, "c"), 300, 122, 200, 10)
	checkRect(t, "d", p.box(t, "d"), 18, 132, 392, 10)
}

func TestInlineLineBreaking(t *testing.T) {
	p := layoutHTML(t, `<!DOCTYPE html><body style="margin:0">
<p id="p" style="width: 100px; font-size: 10px; line-height: 12px; margin: 0">aaa bbb ccc ddd eee fff ggg hhh iii jjj</p>`, "", 800)
	b := p.box(t, "p")
	if len(b.Lines) < 2 {
		t.Fatalf("got %d lines, want wrapping", len(b.Lines))
	}
	if !approx(b.H, float64(len(b.Lines))*12) {
		t.Errorf("height %v for %d lines of 12px", b.H, len(b.Lines))
	}
	for i, l := range b.Lines {
		for _, f := range l.Frags {
			if f.X+f.W > b.X+b.W+0.5 && !f.space {
				t.Errorf("line %d frag %q overflows: %v > %v", i, f.Text, f.X+f.W, b.X+b.W)
			}
		}
	}
}

func TestTextAlign(t *testing.T) {
	p := layoutHTML(t, `<!DOCTYPE html><body style="margin:0">
<div id="c" style="text-align:center">x</div><div id="r" style="text-align:right">x</div>`, "", 400)
	c := p.box(t, "c").Lines[0].Frags[0]
	r := p.box(t, "r").Lines[0].Frags[0]
	if !approx(c.X+c.W/2, 200) {
		t.Errorf("centered frag at %v (w %v)", c.X, c.W)
	}
	if !approx(r.X+r.W, 400) {
		t.Errorf("right-aligned frag ends at %v", r.X+r.W)
	}
}

func TestTableLayout(t *testing.T) {
	p := layoutHTML(t, `<!DOCTYPE html><body style="margin:0">
<table id="t" width="50%" cellspacing="0" cellpadding="0">
<tr id="r1"><td id="a" width="100">a</td><td id="b">b</td></tr>
<tr id="r2" style="height: 40px"><td colspan="2" id="c">c</td></tr>
</table>`, "", 800)
	checkRect(t, "table", p.box(t, "t"), 0, 0, 400, p.box(t, "t").H)
	a, b, c := p.box(t, "a"), p.box(t, "b"), p.box(t, "c")
	ax, ay, aw, _ := a.BorderBox()
	bx, by, bw, _ := b.BorderBox()
	cx, cy, cw, ch := c.BorderBox()
	if !approx(ax, 0) || !approx(aw, 100) || !approx(bx, 100) || !approx(bw, 300) || !approx(ay, by) {
		t.Errorf("row 1 cells: a=(%v,%v w%v) b=(%v,%v w%v)", ax, ay, aw, bx, by, bw)
	}
	if !approx(cx, 0) || !approx(cw, 400) || !approx(ch, 40) || cy <= ay {
		t.Errorf("colspan cell = (%v,%v %vx%v)", cx, cy, cw, ch)
	}
}

func TestCenteredTable(t *testing.T) {
	// <center> centers block-level children such as tables, while in quirks
	// mode the table's own text is reset to start alignment.
	p := layoutHTML(t, `<body style="margin:0"><center><table id="t" width="50%" cellspacing="0" cellpadding="0"><tr><td id="td">x</td></tr></table></center>`, "", 800)
	tx, _, tw, _ := p.box(t, "t").BorderBox()
	if !approx(tx, 200) || !approx(tw, 400) {
		t.Errorf("table at x=%v w=%v, want 200, 400", tx, tw)
	}
	f := p.box(t, "td").Lines[0].Frags[0]
	if !approx(f.X, 200) {
		t.Errorf("cell text at x=%v, want 200 (left aligned)", f.X)
	}
}

func TestShrinkToFitTable(t *testing.T) {
	p := layoutHTML(t, `<!DOCTYPE html><body style="margin:0"><table id="t" cellspacing="0" cellpadding="0"><tr><td><div style="width:120px;height:5px"></div></td></tr></table>`, "", 800)
	_, _, w, h := p.box(t, "t").BorderBox()
	if !approx(w, 120) || !approx(h, 5) {
		t.Errorf("auto table size = %vx%v, want 120x5", w, h)
	}
}
